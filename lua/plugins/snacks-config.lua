-- 使用方法：
-- 1. 在下方 "用户配置区" 的四个列表中添加你要强制显示/隐藏的文件
-- 2. 保存文件后重启 Neovim 生效
-- ============================================================================

-- ============================================================================
-- 用户配置区（你只需要在这里添加/删除文件）
-- ============================================================================

-- 文件查找器 (picker) 配置
-- 强制显示的文件/文件夹
local picker_include = {
  ".i18nrc.lua",
  ".env*",
}
-- 强制隐藏的文件/文件夹
local picker_exclude = {
  "dist",
  "target",
  "logs",
  "node_modules",
  "__pycache__",
  "www",
  "dist*",
  "build",
}

-- ============================================================================
-- 配置主体（不要修改这里）
-- ============================================================================

return {
  {
    "folke/snacks.nvim",
    opts = {
      -- 文件查找器配置
      picker = {
        enabled = true,
        sources = {
          explorer = {
            include = picker_include,
            exclude = picker_exclude,
            hidden = false,
            ignored = true,
          },
        },
      },
    },
  },
}
